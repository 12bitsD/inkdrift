import { useEffect, useRef, useState } from 'react'
import { DEFAULT_PROMPT } from '../shared/types'
import type { ModelProfile, ProfileInput, RunMetadata, RunRecord } from '../shared/types'
import { CodeDialog } from './components/CodeDialog'
import { EmptyArt } from './components/EmptyArt'
import { Icon } from './components/Icon'
import { SettingsDialog } from './components/SettingsDialog'
import { SvgImage } from './components/SvgImage'

function formatDate(value: string): string {
  return new Intl.DateTimeFormat(undefined, { month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' }).format(new Date(value))
}

function formatDuration(milliseconds: number): string {
  return milliseconds < 1000 ? `${String(milliseconds)} ms` : `${(milliseconds / 1000).toFixed(1)} s`
}

function metadata(record: RunRecord): RunMetadata {
  const value: Partial<RunRecord> = { ...record }
  delete value.rawResponse
  delete value.svg
  return value as RunMetadata
}

function HistoryEntry({ run, selected, onSelect }: { run: RunMetadata; selected: boolean; onSelect: () => void }) {
  const [record, setRecord] = useState<RunRecord | null>(null)
  useEffect(() => {
    let active = true
    if (run.hasSvg) window.inkdrift.getRun(run.id).then(value => { if (active) setRecord(value) }).catch(() => {})
    return () => { active = false }
  }, [run.id, run.hasSvg])
  return (
    <li>
      <button type="button" className={selected ? 'history-entry selected' : 'history-entry'} onClick={onSelect} aria-current={selected ? 'true' : undefined}>
        <span className={record?.svg ? 'history-thumb' : 'history-thumb empty'}>
          {record?.svg ? <SvgImage svg={record.svg} alt="" /> : <Icon name={run.status === 'succeeded' ? 'history' : 'close'} size={20} />}
        </span>
        <span className="history-copy"><strong>{run.profileName}</strong><small>{formatDate(run.createdAt)}</small></span>
        <span className={run.status === 'succeeded' ? 'run-mark success' : 'run-mark'} aria-label={run.status} />
      </button>
    </li>
  )
}

function RunPanel({ title, record, emptyTitle, emptyDescription, emptyProfileName, onCode, action }: {
  title: string
  record: RunRecord | null
  emptyTitle: string
  emptyDescription: string
  emptyProfileName?: string
  onCode: (run: RunRecord) => void
  action?: React.ReactNode
}) {
  return (
    <section className="run-panel" aria-labelledby={`${title.toLowerCase()}-heading`}>
      <header className="run-panel-header">
        <div><p className="eyebrow">{title}</p><h2 id={`${title.toLowerCase()}-heading`}>{record?.profileName ?? emptyProfileName ?? 'No selection'}</h2></div>
        {record && <button className="icon-button labelled" type="button" onClick={() => onCode(record)}><Icon name="code" /><span>Raw</span></button>}
      </header>
      <div className={record?.svg ? 'canvas-frame' : 'canvas-frame empty'}>
        {record?.svg ? <SvgImage svg={record.svg} alt={`${title} SVG generated by ${record.profileName}`} /> : <>
          <EmptyArt variant={title === 'BASELINE' ? 'layers' : 'bike'} />
          <div className="empty-copy"><h3>{record?.status === 'failed' ? 'The request did not produce an SVG' : emptyTitle}</h3><p>{record?.errorMessage ?? emptyDescription}</p></div>
        </>}
      </div>
      <footer className="run-panel-footer">
        {record ? <>
          <div className="run-technical"><span>{record.modelId}</span><span>{formatDate(record.createdAt)}</span><span>{formatDuration(record.durationMs)}</span></div>
          {action}
        </> : <span className="technical-placeholder">SVG ONLY · NO SCORE</span>}
      </footer>
    </section>
  )
}

export function App() {
  const [profiles, setProfiles] = useState<ModelProfile[]>([])
  const [activeProfileId, setActiveProfileId] = useState<string | null>(null)
  const [prompt, setPrompt] = useState(DEFAULT_PROMPT)
  const [runs, setRuns] = useState<RunMetadata[]>([])
  const [current, setCurrent] = useState<RunRecord | null>(null)
  const [baseline, setBaseline] = useState<RunRecord | null>(null)
  const [historyFilter, setHistoryFilter] = useState('all')
  const [loading, setLoading] = useState(true)
  const [generating, setGenerating] = useState(false)
  const [settingsOpen, setSettingsOpen] = useState(false)
  const [codeRun, setCodeRun] = useState<RunRecord | null>(null)
  const [error, setError] = useState('')
  const [notice, setNotice] = useState('')
  const baselineRequest = useRef(0)

  useEffect(() => {
    let mounted = true
    window.inkdrift.getState().then(async state => {
      if (!mounted) return
      setProfiles(state.profiles)
      setActiveProfileId(state.activeProfileId)
      setPrompt(state.prompt)
      setRuns(state.runs)
      const latest = state.runs.find(run => run.status === 'succeeded') ?? state.runs[0]
      if (latest) setCurrent(await window.inkdrift.getRun(latest.id))
    }).catch((cause: unknown) => { if (mounted) setError(cause instanceof Error ? cause.message : 'Could not load local data') }).finally(() => { if (mounted) setLoading(false) })
    return () => { mounted = false }
  }, [])

  useEffect(() => {
    const timer = window.setTimeout(() => {
      if (prompt.trim()) window.inkdrift.setPrompt(prompt.trim()).catch(() => {})
    }, 600)
    return () => window.clearTimeout(timer)
  }, [prompt])

  useEffect(() => {
    const request = ++baselineRequest.current
    const timer = window.setTimeout(() => {
      setBaseline(null)
      if (!activeProfileId || !prompt.trim()) return
      window.inkdrift.getBaseline(activeProfileId, prompt.trim()).then(value => {
        if (request === baselineRequest.current) setBaseline(value)
      }).catch(() => {})
    }, 250)
    return () => window.clearTimeout(timer)
  }, [activeProfileId, prompt])

  const selectProfile = async (profileId: string) => {
    setActiveProfileId(profileId)
    setError('')
    await window.inkdrift.setActiveProfile(profileId).catch((cause: unknown) => setError(cause instanceof Error ? cause.message : 'Could not select profile'))
  }

  const selectRun = async (runId: string) => {
    setError('')
    try { setCurrent(await window.inkdrift.getRun(runId)) } catch (cause) { setError(cause instanceof Error ? cause.message : 'Could not open run') }
  }

  const generate = async () => {
    if (!activeProfileId || !prompt.trim() || generating) return
    setGenerating(true)
    setError('')
    setNotice('')
    try {
      const cleanPrompt = prompt.trim()
      setPrompt(cleanPrompt)
      const record = await window.inkdrift.generate(activeProfileId, cleanPrompt)
      setRuns(previous => [metadata(record), ...previous.filter(run => run.id !== record.id)])
      setCurrent(record)
      if (record.status === 'succeeded') setNotice('New frame added to history. Your baseline is unchanged.')
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : 'Generation failed')
    } finally {
      setGenerating(false)
    }
  }

  const saveProfile = async (input: ProfileInput) => {
    const saved = await window.inkdrift.saveProfile(input)
    setProfiles(saved)
    setActiveProfileId(input.id)
    await window.inkdrift.setActiveProfile(input.id)
  }

  const deleteProfile = async (profileId: string) => {
    const remaining = await window.inkdrift.deleteProfile(profileId)
    setProfiles(remaining)
    if (activeProfileId === profileId) setActiveProfileId(null)
  }

  const setAsBaseline = async () => {
    if (!current || current.status !== 'succeeded') return
    setError('')
    try {
      await window.inkdrift.setBaseline(current.id)
      setBaseline(current)
      setNotice('Baseline updated for this model and prompt.')
    } catch (cause) { setError(cause instanceof Error ? cause.message : 'Could not set baseline') }
  }

  const visibleRuns = historyFilter === 'all' ? runs : runs.filter(run => run.profileId === historyFilter)
  const activeProfile = profiles.find(profile => profile.id === activeProfileId)

  return (
    <div className="app-shell">
      <a className="skip-link" href="#workspace">Skip to comparison</a>
      <header className="app-header">
        <div className="brand-block">
          <svg className="brand-mark" viewBox="0 0 36 36" aria-hidden="true"><path d="M7 25 18 4l3 12 8-5-11 21-3-12-8 5Z" fill="currentColor" /></svg>
          <div><h1>inkdrift<span className="brand-period">.</span></h1><p>A visual canary for language models</p></div>
        </div>
        <div className="header-actions">
          <div className="model-selector"><label htmlFor="active-model">MODEL</label><select id="active-model" value={activeProfileId ?? ''} onChange={event => { void selectProfile(event.target.value) }} disabled={generating || profiles.length === 0}><option value="" disabled>{profiles.length ? 'Select a profile' : 'No profiles yet'}</option>{profiles.map(profile => <option key={profile.id} value={profile.id}>{profile.name} · {profile.modelId}</option>)}</select></div>
          <button className="icon-button settings-button" type="button" aria-label="Open model settings" onClick={() => setSettingsOpen(true)}><Icon name="settings" size={20} /></button>
          {generating ? <button className="button primary generate-button" type="button" onClick={() => { void window.inkdrift.cancelGeneration() }}><Icon name="cancel" /> Cancel</button> : <button className="button primary generate-button" type="button" disabled={!activeProfile || !prompt.trim()} onClick={() => { void generate() }}><Icon name="generate" /> Generate</button>}
        </div>
      </header>

      <div className="app-body">
        <aside className="history-sidebar" aria-labelledby="history-title">
          <div className="sidebar-heading"><div><p className="eyebrow">ARCHIVE</p><h2 id="history-title">History <span>{runs.length.toString().padStart(2, '0')}</span></h2></div><Icon name="history" size={20} /></div>
          <search className="history-search"><label htmlFor="history-filter">Filter by model</label><select id="history-filter" value={historyFilter} onChange={event => setHistoryFilter(event.target.value)}><option value="all">All models</option>{profiles.map(profile => <option key={profile.id} value={profile.id}>{profile.name}</option>)}</select></search>
          {visibleRuns.length ? <ul className="history-list">{visibleRuns.map(run => <HistoryEntry key={run.id} run={run} selected={current?.id === run.id} onSelect={() => { void selectRun(run.id) }} />)}</ul> : <div className="history-empty"><EmptyArt variant="layers" /><h3>No frames yet</h3><p>Your generated SVGs will collect here, with the model and time attached.</p></div>}
          <footer className="sidebar-footer"><span className="local-dot" />LOCAL ONLY</footer>
        </aside>

        <main className="workspace" id="workspace">
          <section className="prompt-strip" aria-labelledby="prompt-heading">
            <div className="prompt-number">01</div>
            <div className="prompt-content"><div className="prompt-heading"><h2 id="prompt-heading">The brief</h2><span>One prompt. Two points in time.</span></div><label className="visually-hidden" htmlFor="svg-prompt">SVG generation prompt</label><textarea id="svg-prompt" value={prompt} onChange={event => setPrompt(event.target.value)} disabled={generating} rows={2} maxLength={100000} spellCheck={false} /></div>
            <button className="icon-button prompt-reset" type="button" aria-label="Reset to the Charmander prompt" onClick={() => setPrompt(DEFAULT_PROMPT)} disabled={generating}><Icon name="refresh" /></button>
          </section>

          {(error || notice) && <div className={error ? 'app-message error' : 'app-message'} role={error ? 'alert' : 'status'}><span>{error || notice}</span><button type="button" aria-label="Dismiss message" onClick={() => { setError(''); setNotice('') }}><Icon name="close" size={15} /></button></div>}

          <div className="comparison-grid">
            <RunPanel title="BASELINE" record={baseline} emptyTitle="No baseline for this brief" emptyDescription="Generate an SVG you like, then explicitly save it as your visual reference." onCode={setCodeRun} emptyProfileName={activeProfile?.name} />
            <RunPanel title="CURRENT" record={current} emptyTitle={generating ? 'Drawing a new frame' : activeProfile ? 'Your next SVG lands here' : 'Choose a model to begin'} emptyDescription={generating ? 'Nextloop is running a single turn. Your baseline stays untouched.' : activeProfile ? 'Generate once, compare twice. Nothing is scored automatically.' : 'Open settings to add an OpenAI-compatible model profile.'} onCode={setCodeRun} action={current?.status === 'succeeded' && <div className="current-actions">{baseline?.id !== current.id && <button className="button secondary" type="button" onClick={() => { void setAsBaseline() }}><Icon name="baseline" /> Set as baseline</button>}</div>} />
          </div>
          <footer className="workspace-footer"><span>NO JUDGE</span><span>NO SCORE</span><span>JUST THE FRAMES</span></footer>
        </main>
      </div>

      {loading && <div className="loading-cover"><EmptyArt variant="spark" /><p>Opening the archive…</p></div>}
      <SettingsDialog open={settingsOpen} profiles={profiles} onClose={() => setSettingsOpen(false)} onSave={saveProfile} onDelete={deleteProfile} />
      <CodeDialog run={codeRun} onClose={() => setCodeRun(null)} />
    </div>
  )
}
