import type { RunMetadata, RunRecord } from '../../shared/types'
import type { ActiveGeneration } from '../types'
import { downloadSvg, formatDate, formatDuration } from '../utils'
import { DeleteRunButton } from './DeleteRunButton'
import { EmptyArt } from './EmptyArt'
import { GenerationProgress } from './GenerationProgress'
import { Icon } from './Icon'
import { SvgImage } from './SvgImage'

type RunPanelProps = {
  title: string
  record: RunRecord | null
  busyRun?: ActiveGeneration
  emptyTitle: string
  emptyDescription: string
  emptyProfileName?: string
  onCode: (run: RunRecord) => void
  action?: React.ReactNode
  zoom: number
  onDelete?: (run: RunMetadata) => Promise<void>
  deletePending?: boolean
  deleting?: boolean
}

type PanelActionsProps = Pick<
  RunPanelProps,
  'title' | 'record' | 'onCode' | 'onDelete' | 'deletePending' | 'deleting'
>

function PanelActions({
  title,
  record,
  onCode,
  onDelete,
  deletePending = false,
  deleting = false,
}: PanelActionsProps) {
  if (!record) {
    return null
  }
  return (
    <div className="panel-actions">
      {record.svg && (
        <button
          className="icon-button"
          type="button"
          aria-label={`Download ${title.toLowerCase()} SVG`}
          title="Download SVG"
          onClick={() => downloadSvg(record)}
        >
          <Icon name="download" />
        </button>
      )}
      <button
        className="icon-button labelled"
        type="button"
        onClick={() => onCode(record)}
      >
        <Icon name="code" />
        <span>Raw</span>
      </button>
      {onDelete && (
        <DeleteRunButton
          run={record}
          pending={deletePending}
          deleting={deleting}
          onDelete={onDelete}
          target="current run"
        />
      )}
    </div>
  )
}

function GenerationState({ run }: { run: ActiveGeneration }) {
  return (
    <div className="generation-state" role="status">
      <span className="generation-spinner" aria-hidden="true" />
      <div className="empty-copy">
        <h3>Drawing a new frame</h3>
        <p>
          Nextloop is connecting to {run.modelId}. Your baseline stays
          untouched.
        </p>
      </div>
      <GenerationProgress run={run} />
    </div>
  )
}

function EmptyState({ title, record, emptyTitle, emptyDescription }: {
  title: string
  record: RunRecord | null
  emptyTitle: string
  emptyDescription: string
}) {
  let heading = emptyTitle
  if (record?.status === 'failed') {
    heading = 'The request did not produce an SVG'
  } else if (record?.status === 'cancelled') {
    heading = 'Generation cancelled'
  }
  return (
    <>
      <EmptyArt variant={title === 'BASELINE' ? 'layers' : 'bike'} />
      <div className="empty-copy">
        <h3>{heading}</h3>
        <p>{record?.errorMessage ?? emptyDescription}</p>
      </div>
    </>
  )
}

function PanelContent({
  title,
  record,
  busyRun,
  emptyTitle,
  emptyDescription,
  zoom,
}: RunPanelProps) {
  if (busyRun) {
    return <GenerationState run={busyRun} />
  }
  if (record?.svg) {
    const altText = [
      `${title} SVG generated by`,
      record.profileName,
    ].join(' ')
    return (
      <div
        className="svg-zoom-layer"
        style={{
          inlineSize: `${String(zoom)}%`,
          blockSize: `${String(zoom)}%`,
        }}
      >
        <SvgImage
          svg={record.svg}
          alt={altText}
          eager
        />
      </div>
    )
  }
  return (
    <EmptyState
      title={title}
      record={record}
      emptyTitle={emptyTitle}
      emptyDescription={emptyDescription}
    />
  )
}

function PanelFooter({ busyRun, record, action }: {
  busyRun?: ActiveGeneration
  record: RunRecord | null
  action?: React.ReactNode
}) {
  if (busyRun) {
    return (
      <div className="run-technical">
        <span>{busyRun.modelId}</span>
        <span>Running…</span>
      </div>
    )
  }
  if (!record) {
    return <span className="technical-placeholder">SVG ONLY · NO SCORE</span>
  }
  return (
    <>
      <div className="run-technical">
        <span>{record.modelId}</span>
        <span>{formatDate(record.createdAt)}</span>
        <span>{formatDuration(record.durationMs)}</span>
      </div>
      {action}
    </>
  )
}

export function RunPanel({
  title,
  record,
  busyRun,
  emptyTitle,
  emptyDescription,
  emptyProfileName,
  onCode,
  action,
  zoom,
  onDelete,
  deletePending,
  deleting,
}: RunPanelProps) {
  let frameClass = 'canvas-frame empty'
  if (busyRun) {
    frameClass = 'canvas-frame empty generating-frame'
  } else if (record?.svg) {
    frameClass = 'canvas-frame'
  }
  const profileName = record?.profileName
    ?? busyRun?.profileName
    ?? emptyProfileName
    ?? 'No selection'
  return (
    <section className="run-panel" aria-labelledby={`${title.toLowerCase()}-heading`}>
      <header className="run-panel-header">
        <div className="run-panel-title">
          <p className="eyebrow">{title}</p>
          <h2 id={`${title.toLowerCase()}-heading`}>{profileName}</h2>
        </div>
        {!busyRun && (
          <PanelActions
            title={title}
            record={record}
            onCode={onCode}
            onDelete={onDelete}
            deletePending={deletePending}
            deleting={deleting}
          />
        )}
      </header>
      <div className={frameClass} aria-busy={Boolean(busyRun)}>
        <PanelContent
          title={title}
          record={record}
          busyRun={busyRun}
          emptyTitle={emptyTitle}
          emptyDescription={emptyDescription}
          emptyProfileName={emptyProfileName}
          onCode={onCode}
          action={action}
          zoom={zoom}
          onDelete={onDelete}
          deletePending={deletePending}
          deleting={deleting}
        />
      </div>
      <footer className="run-panel-footer">
        <PanelFooter
          busyRun={busyRun}
          record={record}
          action={action}
        />
      </footer>
    </section>
  )
}
